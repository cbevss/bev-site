"""Writes site/lang.js (translations) from tools/lang_strings.py and stamps its version into nav.js."""
import hashlib, json, re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from lang_strings import LANGS, T
root = pathlib.Path(__file__).parent.parent / "site"
for k, v in T.items():
    assert len(v) == len(LANGS), k
data = {l: {k: v[i] for k, v in T.items()} for i, l in enumerate(LANGS)}
js = "/* Generated by tools/build_lang.py: do not edit by hand. */\nwindow.BEV_LANG_DATA=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "lang.js").write_text(js, encoding="utf-8")
v = hashlib.sha256(js.encode()).hexdigest()[:10]
nav = (root / "nav.js").read_text(encoding="utf-8")
nav2 = re.sub(r"var LANG_V = '[0-9a-f]*';", "var LANG_V = '%s';" % v, nav)
(root / "nav.js").write_text(nav2, encoding="utf-8")
print("lang.js", len(js), "bytes, v", v)
